// Wraps web/ossa.html (the whole app) into a module the WebView can load. Runs automatically before `npm start`.
// The new UI layer lives in web/ui/. Pull a file in with a marker on its own line:
//   /*@include ui/tokens.css*/   inside a <style> block
//   /*@include ui/shell.js*/     inside a <script> block
//   /*@include-preview ui/x.js*/ the same, but only in web/.preview.html: it never reaches ossaHtml.js
//                                (desktop-only experiments, behind a localhost check as well)
// Also writes web/.preview.html, a full page you can open in a desktop browser.
const fs = require("fs");
const path = require("path");
const WEB = path.join(__dirname, "..", "web");

function inline(src, seen, preview) {
  return src.replace(/^[ \t]*\/\*@include(-preview)? ([\w./-]+)\*\/[ \t]*$/gm, (_, only, rel) => {
    const file = path.join(WEB, rel);
    if (seen.has(file)) throw new Error("build-html: include loop at " + rel);
    if (!fs.existsSync(file)) throw new Error("build-html: missing include " + rel);
    if (only && !preview) return "";
    return `/* ---- ${rel} ---- */\n` + inline(fs.readFileSync(file, "utf8"), new Set([...seen, file]), preview);
  });
}

const src = fs.readFileSync(path.join(WEB, "ossa.html"), "utf8");
const page = body => `<!doctype html><html lang="en-GB"><head><meta charset="utf-8">
<meta name="viewport" id="ossaVp" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover">
<script>/* 21 Oct: a phone narrower than 360 (an iPhone with Display Zoom, an SE, small Androids) lays out the 375-wide design scaled to fit, instead of squashing it */
(function(){try{var w=Math.min(screen.width||0,screen.height||0)||window.innerWidth;if(w&&w<360){document.getElementById("ossaVp").setAttribute("content","width=375,user-scalable=no,viewport-fit=cover");document.documentElement.setAttribute("data-vp","375");}}catch(e){}})();</script>
<style>html,body{margin:0;background:#000;height:100%;overscroll-behavior:none;-webkit-tap-highlight-color:transparent;-webkit-user-select:none;user-select:none}[hidden]{display:none!important}input,textarea{-webkit-user-select:text;user-select:text}</style>
</head><body>${body}</body></html>`;
const DEV = process.env.OSSA_DEV === "1";   // Expo Go testing: the preview-only files (devpro.js) go into ossaHtml.js too. Never on Codemagic.
if (DEV) console.warn("build-html: OSSA_DEV=1, development-only code is in ossaHtml.js. Do not ship this bundle; Codemagic rebuilds it without the flag.");
const html = page(inline(src, new Set(), DEV));
const preview = page(inline(src, new Set(), true));
fs.writeFileSync(path.join(__dirname, "..", "ossaHtml.js"), "// Generated by scripts/build-html.js. Edit web/ossa.html and web/ui/ instead.\nexport default " + JSON.stringify(html) + ";\n");
fs.writeFileSync(path.join(WEB, ".preview.html"), preview);
console.log("Ossa: packed web/ossa.html (" + Math.round(html.length / 1024) + " KB)" +
  (preview.length > html.length ? ", plus " + Math.round((preview.length - html.length) / 1024) + " KB preview-only in web/.preview.html" : ""));
