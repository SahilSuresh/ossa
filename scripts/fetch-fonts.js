// Downloads Ossa's typeface, Inter (Latin subset), from Google Fonts once and writes
// web/ui/fonts.css with it embedded, so the app's first launch works offline.
// Roman 300-900 plus a true italic at 800-900 for impact headlines.
// Inter is SIL Open Font License 1.1 (credited in Settings > Open-source licences).
// Re-run only if you change the family or weights.
// Run: node scripts/fetch-fonts.js
const fs = require("fs");
const path = require("path");

const CSS_URL = "https://fonts.googleapis.com/css2?family=Inter:ital,wght@0,300..900;1,800..900&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
const OUT = path.join(__dirname, "..", "web", "ui", "fonts.css");

(async () => {
  const css = await (await fetch(CSS_URL, { headers: { "user-agent": UA } })).text();
  // keep only the Latin blocks: "/* latin */ @font-face { ... }"
  const blocks = [...css.matchAll(/\/\* (latin) \*\/\s*(@font-face\s*{[^}]+})/g)].map(m => m[2]);
  if (!blocks.length) throw new Error("no Latin @font-face blocks found");
  let out = "/* Generated by scripts/fetch-fonts.js — Inter (SIL OFL 1.1), Latin subset, roman 300-900 and italic 800-900, embedded so the app works offline. */\n";
  let bytes = 0;
  for (const b of blocks) {
    const url = (b.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    if (!url) continue;
    const buf = Buffer.from(await (await fetch(url, { headers: { "user-agent": UA } })).arrayBuffer());
    bytes += buf.length;
    // the italic face (800-900) gets its own family, used only by .u-impact: other italic text then slants the roman instead of turning extra-bold
    const face = /font-style:\s*italic/.test(b) ? b.replace(/font-family:\s*'Inter'/, "font-family: 'Inter Display Italic'") : b;
    out += face.replace(url, "data:font/woff2;base64," + buf.toString("base64")).replace(/\n\s*/g, "") + "\n";
  }
  fs.writeFileSync(OUT, out);
  console.log(`Ossa: wrote web/ui/fonts.css (${blocks.length} faces, ${Math.round(bytes / 1024)} KB of fonts)`);
})().catch(e => { console.error(e.message || e); process.exit(1); });
